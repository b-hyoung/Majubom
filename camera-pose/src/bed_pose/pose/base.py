"""Project-owned synchronous adapter boundary (not an SDK interface)."""
from typing import Protocol
from bed_pose.contracts import ModelInput, PoseOutput


class PoseAdapter(Protocol):
    def open(self, settings: dict) -> dict: ...
    def reset_for_video(self) -> dict: ...
    def estimate(self, frame: ModelInput) -> PoseOutput: ...
    def close(self) -> None: ...
